"""Clearly-labelled sample articles for demo mode.

These are NOT real news.  Every title starts with ``[DEMO]``, every URL points
to ``example.com`` and every source id starts with ``demo-`` so the data can
never be mistaken for - or mixed up with - live headlines.
"""
from __future__ import annotations

from datetime import datetime, timedelta, timezone
from typing import List, Optional

from models import Article

_SOURCES = {
    "wire": ("Demo Wire", "demo-wire"),
    "tech": ("Demo Tech Review", "demo-tech"),
    "sport": ("Demo Sports Desk", "demo-sports"),
    "health": ("Demo Health Journal", "demo-health"),
    "biz": ("Demo Business Daily", "demo-business"),
}

# (source key, category, headline, hours-ago)
_SAMPLES = [
    ("tech", "technology", "Sample story: a new open-source toolkit makes desktop apps easier to build", 2),
    ("tech", "technology", "Sample story: developers compare Python GUI frameworks for dashboards", 7),
    ("tech", "technology", "Sample story: why database indexes matter for fast search", 26),
    ("tech", "science", "Sample story: researchers explain how weather models are verified", 30),
    ("wire", "science", "Sample story: students build a low-cost air quality sensor network", 50),
    ("wire", "general", "Sample story: local library extends opening hours for exam season", 5),
    ("wire", "general", "Sample story: community garden project reaches its first harvest", 28),
    ("wire", "general", "Sample story: city council publishes an open data portal", 52),
    ("biz", "business", "Sample story: small businesses adopt spreadsheets-to-database migrations", 4),
    ("biz", "business", "Sample story: how freelancers track invoices with simple tools", 29),
    ("biz", "business", "Sample story: remote teams share tips on asynchronous communication", 75),
    ("sport", "sports", "Sample story: amateur league announces a new season schedule", 3),
    ("sport", "sports", "Sample story: coaches discuss training habits that prevent injuries", 27),
    ("sport", "sports", "Sample story: marathon organisers publish route updates", 51),
    ("health", "health", "Sample story: nutrition basics - building a balanced weekly meal plan", 6),
    ("health", "health", "Sample story: sleep experts explain consistent bedtime routines", 31),
    ("health", "health", "Sample story: simple desk exercises for long working days", 76),
    ("wire", "entertainment", "Sample story: independent film festival opens its programme", 8),
    ("wire", "entertainment", "Sample story: music students record a charity album", 32),
    ("tech", "entertainment", "Sample story: indie game studio shares its development diary", 53),
]

_BODY = ("This is DEMO content generated by NewsPulse so you can explore the app without an API key. "
         "It is not a real news article. Add a NewsAPI key in Settings to see live headlines.")


def build_demo_articles(now: Optional[datetime] = None) -> List[Article]:
    """Return the sample articles with timestamps relative to ``now``."""
    now = now or datetime.now(timezone.utc)
    articles = []
    for index, (src, category, headline, hours_ago) in enumerate(_SAMPLES, start=1):
        name, api_id = _SOURCES[src]
        published = (now - timedelta(hours=hours_ago)).strftime("%Y-%m-%dT%H:%M:%SZ")
        articles.append(Article(
            title=f"[DEMO] {headline}",
            url=f"https://example.com/newspulse-demo/{index:02d}",
            source_name=name, source_api_id=api_id,
            description=f"[DEMO] {_BODY}", content=_BODY,
            author="NewsPulse Demo", image_url="", published_at=published,
            category=category, is_demo=True,
        ))
    return articles
